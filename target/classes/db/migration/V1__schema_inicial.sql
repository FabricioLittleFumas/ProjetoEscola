CREATE SEQUENCE IF NOT EXISTS sq_aluno START WITH 100 INCREMENT BY 100;
CREATE SEQUENCE IF NOT EXISTS sq_user START WITH 100 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS aluno (
    id BIGINT NOT NULL DEFAULT nextval('sq_aluno'),
    nome VARCHAR(255) NOT NULL,
    registro_matricula INTEGER NOT NULL DEFAULT 0,
    data_saida DATE,
    unidade VARCHAR(255),
    CONSTRAINT pk_aluno PRIMARY KEY (id)
);

ALTER TABLE aluno ADD COLUMN IF NOT EXISTS registro_matricula INTEGER;
UPDATE aluno SET registro_matricula = id WHERE registro_matricula IS NULL;
ALTER TABLE aluno ALTER COLUMN registro_matricula SET DEFAULT 0;
ALTER TABLE aluno ALTER COLUMN registro_matricula SET NOT NULL;
ALTER TABLE aluno ADD COLUMN IF NOT EXISTS data_saida DATE;
ALTER TABLE aluno ADD COLUMN IF NOT EXISTS unidade VARCHAR(255);
CREATE UNIQUE INDEX IF NOT EXISTS uk_aluno_nome ON aluno (nome);

CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER NOT NULL DEFAULT nextval('sq_user'),
    user_name VARCHAR(255) NOT NULL,
    user_passwd VARCHAR(255) NOT NULL,
    user_email VARCHAR(255) NOT NULL,
    approved BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT pk_users PRIMARY KEY (user_id)
);

ALTER TABLE users ADD COLUMN IF NOT EXISTS approved BOOLEAN NOT NULL DEFAULT FALSE;
CREATE UNIQUE INDEX IF NOT EXISTS uk_users_user_email ON users (user_email);

CREATE TABLE IF NOT EXISTS roles (
    user_id INTEGER NOT NULL,
    user_role VARCHAR(255),
    CONSTRAINT fk_roles_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(500) NOT NULL,
    user_id INTEGER NOT NULL,
    expiry_date TIMESTAMP NOT NULL,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (user_id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_refresh_tokens_token ON refresh_tokens (token);

CREATE TABLE IF NOT EXISTS log_system (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    acao TEXT NOT NULL,
    usuario_id INTEGER NOT NULL,
    data_hora TIMESTAMP NOT NULL,
    CONSTRAINT fk_log_system_usuario FOREIGN KEY (usuario_id) REFERENCES users (user_id)
);

ALTER TABLE log_system ALTER COLUMN acao TYPE TEXT;
